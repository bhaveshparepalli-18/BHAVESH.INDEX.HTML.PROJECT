-- SUPABASE DATABASE SCHEMA FOR AMAZON SHOPPING MALL
-- Copy and paste this into the Supabase SQL Editor and click RUN
-- ===================================================================

-- 1. Create PRODUCTS table
CREATE TABLE IF NOT EXISTS public.products (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  brand TEXT NOT NULL,
  price NUMERIC(10, 2) NOT NULL,
  original_price NUMERIC(10, 2),
  rating NUMERIC(3, 2) DEFAULT 5.0,
  reviews INTEGER DEFAULT 0,
  badge TEXT,
  is_prime BOOLEAN DEFAULT true,
  is_deal BOOLEAN DEFAULT false,
  in_stock BOOLEAN DEFAULT true,
  image TEXT,
  description TEXT,
  specs JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create ORDERS table
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id TEXT UNIQUE NOT NULL,
  customer_name TEXT NOT NULL,
  customer_phone TEXT,
  street_address TEXT,
  city TEXT,
  state TEXT,
  zip_code TEXT,
  payment_method TEXT DEFAULT 'card',
  items JSONB NOT NULL,
  subtotal NUMERIC(10, 2) NOT NULL,
  tax NUMERIC(10, 2) NOT NULL,
  grand_total NUMERIC(10, 2) NOT NULL,
  status TEXT DEFAULT 'Processing',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- 4. Create Policies for Public Access
-- Allow anyone to view products
CREATE POLICY "Allow public read access on products"
  ON public.products
  FOR SELECT
  USING (true);

-- Allow anyone to insert products (for initial catalog seeding)
CREATE POLICY "Allow insert access on products"
  ON public.products
  FOR INSERT
  WITH CHECK (true);

-- Allow anyone to insert orders (customers placing orders)
CREATE POLICY "Allow public to place orders"
  ON public.orders
  FOR INSERT
  WITH CHECK (true);

-- Allow viewing orders
CREATE POLICY "Allow public read on orders"
  ON public.orders
  FOR SELECT
  USING (true);
